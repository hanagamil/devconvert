/**
 * Shared helpers for discovering object arrays in JSON data structures.
 * These are used by multiple converters, so they do not belong to a format-specific module.
 */

export function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

export interface ArrayCandidate {
  path: string
  value: Record<string, unknown>[]
}

function isObjectArray(value: unknown): value is Record<string, unknown>[] {
  return Array.isArray(value) && value.length > 0 && value.every(isRecord)
}

/**
 * Finds non-empty arrays of objects anywhere inside a parsed JSON value.
 * Paths use dot notation, with "$" representing a top-level array.
 */
export function findObjectArrays(input: unknown): ArrayCandidate[] {
  const candidates: ArrayCandidate[] = []

  function visit(value: unknown, path: string): void {
    if (Array.isArray(value)) {
      if (isObjectArray(value)) {
        candidates.push({ path: path || '$', value })
      }
      value.forEach((item, index) => {
        if (isRecord(item) || Array.isArray(item)) {
          visit(item, `${path}[${index}]`)
        }
      })
      return
    }

    if (isRecord(value)) {
      for (const [key, child] of Object.entries(value)) {
        const childPath = path ? `${path}.${key}` : key
        visit(child, childPath)
      }
    }
  }

  visit(input, '')
  return candidates
}

/**
 * Reads a discovered array path from a parsed JSON value.
 */
export function getValueAtPath(input: unknown, path: string): unknown {
  if (path === '$') return input

  // Paths generated by findObjectArrays support object keys and array indexes.
  const parts = path.match(/[^.[\]]+|\[\d+\]/g) ?? []
  let current: unknown = input

  for (const part of parts) {
    if (part.startsWith('[') && part.endsWith(']')) {
      const index = Number(part.slice(1, -1))
      current = Array.isArray(current) ? current[index] : undefined
    } else {
      current = isRecord(current) ? current[part] : undefined
    }
  }

  return current
}
